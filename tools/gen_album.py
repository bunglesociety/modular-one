"""The album of the Amorph patch "Evolving still frame" (Alexis Arakis) for the demo mode.

Reads the note tables of the patch (dsp.cmajor: nS start s, nN note, nV velocity 0..1, nD length s,
nL layer) and writes firmware/src/album_data.h, one packed stream:
  per note: dt (from the previous start, 10 ms), note, vel (1..127), len (20 ms)
  dt and len: one byte below 128, else two (high bit set first, then 7 + 8 bits)
  python3 tools/gen_album.py PATH/dsp.cmajor
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1]).read_text()
ev = {}
for m in re.finditer(r'nS\[(\d+)\]=([\d.]+)f; nN\[\d+\]=(\d+); nV\[\d+\]=([\d.]+)f; nD\[\d+\]=([\d.]+)f; nL\[\d+\]=(\d+);', src):
    ev[int(m[1])] = (float(m[2]), int(m[3]), float(m[4]), float(m[5]), int(m[6]))
notes = sorted(ev.values())


def var(v):
    v = max(0, min(v, 0x7FFF))
    return [v] if v < 128 else [0x80 | (v >> 8), v & 255]


out, prev = [], 0
for s, n, v, d, layer in notes:
    t = int(round(s * 100))
    out += var(t - prev)
    out += [n, max(1, min(127, int(round(v * 127)))), *var(max(1, int(round(d * 50))))]
    prev = t
end = max(s + d for s, n, v, d, _ in notes)

dst = Path(__file__).resolve().parent.parent / 'firmware' / 'src' / 'album_data.h'
with open(dst, 'w') as f:
    f.write('/* "Evolving still frame", the album of the Amorph patch by Alexis Arakis: %d notes, %.1f min.\n'
            ' * Generated by tools/gen_album.py: dt (10 ms), note, vel, len (20 ms); dt / len: 1 byte < 128,\n'
            ' * else 2 (high bit first) */\n' % (len(notes), end / 60))
    f.write('#define AL_N %d\n#define AL_BYTES %d\nstatic const uint8_t AL_DATA[AL_BYTES] = {\n' % (len(notes), len(out)))
    for i in range(0, len(out), 24):
        f.write('    ' + ','.join(str(b) for b in out[i:i + 24]) + ',\n')
    f.write('};\n')
print('%d notes, %.1f min, %d bytes' % (len(notes), end / 60, len(out)))
