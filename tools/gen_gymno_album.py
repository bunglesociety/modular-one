"""The public demo of the MIDI player: Erik Satie's 1st Gymnopedie (1888, public domain).

Reads firmware/src/gymno_data.h (tools/gen_gymno.py, from the Mutopia Project source) and writes
firmware/src/album_data.h in the player's packed format (see tools/gen_album.py):
  per note: dt (from the previous start, 10 ms), note, vel, len (20 ms); dt / len: 1 or 2 bytes
72 BPM; each note ends an eighth of a quarter before its written end.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = (ROOT / 'firmware' / 'src' / 'gymno_data.h').read_text()
BPM = 72
QS = 60.0 / BPM                                   # seconds per quarter

ev = []
for m in re.finditer(r'\{(\d+), (\d+), (\d+), (\d+), (\d+)\}', SRC):
    lo, hi, note, ln, vel = map(int, m.groups())
    ev.append((lo | hi << 8, note, ln, vel))
ev.sort()


def var(v):
    v = max(0, min(v, 0x7FFF))
    return [v] if v < 128 else [0x80 | (v >> 8), v & 255]


out, prev = [], 0
for q, note, ln, vel in ev:
    t = int(round(q * QS * 100))
    out += var(t - prev)
    out += [note, max(1, min(127, vel)), *var(max(1, int(round((ln - 0.125) * QS * 50))))]
    prev = t
end = max((q + ln) * QS for q, _, ln, _ in ev)

dst = ROOT / 'firmware' / 'src' / 'album_data.h'
with open(dst, 'w') as f:
    f.write('/* Erik Satie, 1ere Gymnopedie (1888, public domain), the demo of the MIDI player: %d notes, %.1f min.\n'
            ' * Generated by tools/gen_gymno_album.py from gymno_data.h (Mutopia Project source).\n'
            ' * dt (10 ms), note, vel, len (20 ms); dt / len: 1 byte < 128, else 2 (high bit first) */\n'
            % (len(ev), end / 60))
    f.write('#define AL_MAXLEN 220500u   /* up to 5 s: the long bass notes and chords of the piece */\n')
    f.write('#define AL_N %d\n#define AL_BYTES %d\nstatic const uint8_t AL_DATA[AL_BYTES] = {\n' % (len(ev), len(out)))
    for i in range(0, len(out), 24):
        f.write('    ' + ','.join(str(b) for b in out[i:i + 24]) + ',\n')
    f.write('};\n')
print('%d notes, %.1f min, %d bytes' % (len(ev), end / 60, len(out)))
