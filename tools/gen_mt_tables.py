"""Tables of the Modular Town FM engine and effects -> firmware/src/mt_tables.h
   python3 tools/gen_mt_tables.py firmware/src/mt_tables.h
The curves are the ones of the Modular Town V2 Cmajor patch (IndustrieSynth in winter,
DreamFX), sampled so that the firmware needs no floating point."""
import math
import sys

FS = 44100


def arr(name, typ, vals, comment, per=12):
    s = f"/* {comment} */\nstatic const {typ} {name}[{len(vals)}] = {{\n"
    for i in range(0, len(vals), per):
        s += "    " + ", ".join(str(v) for v in vals[i:i + per]) + ",\n"
    return s + "};\n"


def main(path):
    out = ["/* SPDX-License-Identifier: GPL-3.0-only\n * Copyright (C) 2026 Alexis Arakis (Bungle Society) */\n",
           "/* generated by tools/gen_mt_tables.py: do not edit */\n#pragma once\n#include <stdint.h>\n"]
    out.append(arr("MT_IDX_Q12", "uint16_t", [round(4096 * 1.8 * (i / 128) ** 1.5) for i in range(129)],
                   "FM index from the brightness c = i/128: c * sqrt(c) * 1.8, Q12"))
    out.append(arr("MT_RESG_Q15", "uint16_t", [min(32767, round(32768 / (1 + 3.8 * i / 128))) for i in range(129)],
                   "level loss of the resonance r = i/128 (as the ladder): 1 / (1 + 3.8 r), Q15"))
    out.append(arr("MT_TRK_Q15", "uint16_t",
                   [min(32767, round(32768 / math.sqrt(1 + 2 ** (4 * (d - 64) / 12)))) for d in range(129)],
                   "a note above the brightness fades: 1 / sqrt(1 + (f / fc)^4), d = note - cutoff note + 64 (semitones), Q15"))
    out.append(arr("MT_KF_Q15", "uint16_t",
                   [min(32767, round(32768 * min(1, math.sqrt(1500 / (440 * 2 ** ((n - 69) / 12)))))) for n in range(128)],
                   "high notes get less index: min(1, sqrt(1500 Hz / f)) per MIDI note, Q15"))
    out.append(arr("MT_FMLP_Q15", "uint16_t",
                   [round(32768 * (1 - math.exp(-2 * math.pi * (14000 - 12200 * i / 16) / FS))) for i in range(17)],
                   "soft low-pass of each voice, closing at night (i/16): one-pole at 14 kHz .. 1.8 kHz, Q15"))
    out.append(arr("MT_DLP_Q15", "uint16_t",
                   [round(32768 * (1 - math.exp(-2 * math.pi * (3400 - 2100 * i / 16) / FS))) for i in range(17)],
                   "island veil: one-pole at 3.4 kHz .. 1.3 kHz as the island fades in (i/16), Q15"))
    out.append(arr("MT_DET_Q16", "uint32_t", [round(65536 * 2 ** ((d - 192) / 192)) for d in range(385)],
                   "CLOCH: modulator 2 detune 2^(d / 12) for d = -12 .. +12 semitones in 1/16 steps, Q16"))
    with open(path, "w") as f:
        f.write("".join(out))
    print(f"mt tables: {path}")


if __name__ == "__main__":
    main(sys.argv[1])
